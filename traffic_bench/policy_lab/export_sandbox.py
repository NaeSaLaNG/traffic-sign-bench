"""Build the agent's sandbox from an allowlist of files.

Nothing is copied by default: the sandbox gets the template in
``sandbox_template/``, the CaRL network code (``third_party/CaRL/nuPlan``), a
standalone copy of ``carl_adapter.py`` and the list of plate names. No git
history, no ``__pycache__``, no benchmark package. A final scan refuses to
finish if any exported text file mentions the benchmark or its rule code.

    python -m traffic_bench.policy_lab.export_sandbox --out $LAB/sandbox
"""
from __future__ import annotations

import argparse
import shutil
from pathlib import Path

from traffic_bench.eval.sign_registry import repo_root

HERE = Path(__file__).resolve().parent
TEMPLATE = HERE / "sandbox_template"
MARKER = ".policy_lab_sandbox"

# Strings that must not appear in any exported text file.
LEAK_MARKERS = (
    "traffic_bench", "traffic-sign-bench", "check_violation", "_is_violating",
    "SignComplianceMixin", "carl_rule", "sign_eval", "traffic_sign_manager",
)
TEXT_SUFFIXES = {".py", ".md", ".txt", ".yaml", ".yml", ".json", ".cfg", ".toml", ".sh", ".ini"}
IGNORE = shutil.ignore_patterns("__pycache__", "*.pyc", ".git", ".github", "*.egg-info", ".DS_Store")

_ADAPTER_IMPORT = '''        CARL_PATH = os.environ.get("CARL_NUPLAN_PATH")
        if not CARL_PATH:
            from traffic_bench.eval.sign_registry import repo_root
            CARL_PATH = str(repo_root() / "third_party" / "CaRL" / "nuPlan")
'''
_ADAPTER_IMPORT_SANDBOX = '''        CARL_PATH = os.environ.get("CARL_NUPLAN_PATH")
        if not CARL_PATH:
            raise RuntimeError("CARL_NUPLAN_PATH is not set")
'''

_EXTRACTOR_IMPORT = (
    "            from traffic_bench.agents.adapters.carl.metadrive_extractor import MetaDriveExtractor\n"
)
_EXTRACTOR_IMPORT_SANDBOX = (
    "            raise RuntimeError(\"the BEV arrives in obs['bev']; map extraction runs in the simulator\")\n"
)


def _standalone_adapter(src: Path) -> str:
    text = src.read_text(encoding="utf-8")
    if text.count(_ADAPTER_IMPORT) != 1:
        raise RuntimeError(f"{src}: CaRL path lookup changed; update export_sandbox._ADAPTER_IMPORT")
    text = text.replace(_ADAPTER_IMPORT, _ADAPTER_IMPORT_SANDBOX)
    if text.count(_EXTRACTOR_IMPORT) != 1:
        raise RuntimeError(f"{src}: extractor import changed; update export_sandbox._EXTRACTOR_IMPORT")
    text = text.replace(_EXTRACTOR_IMPORT, _EXTRACTOR_IMPORT_SANDBOX)
    text = text.replace("        # CARL_NUPLAN_PATH lets the policy-lab sandbox load the network\n"
                        "        # without the benchmark package next to it.\n", "")
    return text


def _plate_names(root: Path) -> list[str]:
    icons = root / "traffic_bench" / "signs" / "icons"
    return sorted(p.stem for p in icons.glob("*.png"))


def scan_for_leaks(out: Path) -> list[str]:
    hits = []
    for path in out.rglob("*"):
        if path.is_symlink():
            hits.append(f"{path}: symlink")
            continue
        if not path.is_file() or path.suffix not in TEXT_SUFFIXES:
            continue
        text = path.read_text(encoding="utf-8", errors="ignore")
        for marker in LEAK_MARKERS:
            if marker in text:
                hits.append(f"{path.relative_to(out)}: {marker!r}")
    return hits


def export(out: Path, force: bool = False, with_plates: bool = True) -> Path:
    root = repo_root().resolve()
    out = Path(out).resolve()
    if out == root or root in out.parents:
        raise SystemExit("export the sandbox outside the repository")
    if out.exists() and any(out.iterdir()):
        if not force or not (out / MARKER).exists():
            raise SystemExit(f"{out} is not empty (use --force to replace a previous sandbox)")
        shutil.rmtree(out)
    out.mkdir(parents=True, exist_ok=True)

    carl_src = root / "third_party" / "CaRL" / "nuPlan"
    if not (carl_src / "carl_nuplan").is_dir():
        raise SystemExit(f"{carl_src} not found: run `git submodule update --init third_party/CaRL`")

    shutil.copytree(TEMPLATE, out, dirs_exist_ok=True, ignore=IGNORE)
    adapter = root / "traffic_bench" / "agents" / "adapters" / "carl" / "carl_adapter.py"
    (out / "carl_sandbox" / "carl_adapter.py").write_text(_standalone_adapter(adapter), encoding="utf-8")
    shutil.copytree(carl_src, out / "third_party" / "CaRL" / "nuPlan", ignore=IGNORE)
    carl_license = root / "third_party" / "CaRL" / "LICENSE"
    if carl_license.is_file():
        shutil.copy2(carl_license, out / "third_party" / "CaRL" / "LICENSE")
    if with_plates:
        (out / "plates.txt").write_text("\n".join(_plate_names(root)) + "\n", encoding="utf-8")

    leaks = scan_for_leaks(out)
    if leaks:
        shutil.rmtree(out)
        raise SystemExit("export aborted, sandbox would leak:\n  " + "\n  ".join(leaks))
    (out / MARKER).write_text("generated by traffic_bench.policy_lab.export_sandbox\n", encoding="utf-8")
    return out


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", required=True, type=Path)
    ap.add_argument("--force", action="store_true", help="replace an existing sandbox")
    ap.add_argument("--no-plates", action="store_true", help="do not ship the list of plate names")
    args = ap.parse_args()
    out = export(args.out, force=args.force, with_plates=not args.no_plates)
    print(f"sandbox: {out}")


if __name__ == "__main__":
    main()
